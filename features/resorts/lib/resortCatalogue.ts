export const buildPhotoUrl = (photo: ResortPhoto, width = 1200): string => {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(photo.file)}?width=${width}`;
};

export const photoSourceUrl = (photo: ResortPhoto): string => {
  return `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(photo.file)}`;
};

export const resortInfo = (key: string | undefined): ResortInfo | undefined => {
  if (!key) return undefined;
  const entry = RESORT_INFO[key];
  if (!entry) return undefined;
  if (entry.sharesCardWith) {
    const parent = RESORT_INFO[entry.sharesCardWith];
    if (parent) return { ...parent, name: entry.name };
  }
  return entry;
};
